CREATE TABLE resumen_diario_lectura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resumen_id BIGINT NOT NULL,
    tutor_id BIGINT NOT NULL,
    visto_en TIMESTAMP NOT NULL,
    CONSTRAINT uq_resumen_lectura_tutor UNIQUE (resumen_id, tutor_id),
    CONSTRAINT fk_resumen_lectura_resumen FOREIGN KEY (resumen_id) REFERENCES resumen_diario (id),
    CONSTRAINT fk_resumen_lectura_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE INDEX ix_resumen_lectura_tutor ON resumen_diario_lectura (tutor_id, resumen_id);
