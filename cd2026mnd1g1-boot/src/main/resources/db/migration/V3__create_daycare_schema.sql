SET DATABASE SQL SYNTAX PGS TRUE;

CREATE TABLE centro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    cif VARCHAR(20) NOT NULL UNIQUE,
    direccion VARCHAR(255) NOT NULL,
    codigo_postal VARCHAR(12),
    localidad VARCHAR(120),
    telefono VARCHAR(30),
    email VARCHAR(254),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_centro_tipo CHECK (tipo IN ('PROPIA', 'CLIENTE'))
);

CREATE TABLE rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(500)
);

CREATE TABLE permiso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(120) NOT NULL UNIQUE,
    descripcion VARCHAR(500)
);

CREATE TABLE rol_permiso (
    rol_id BIGINT NOT NULL,
    permiso_id BIGINT NOT NULL,
    CONSTRAINT pk_rol_permiso PRIMARY KEY (rol_id, permiso_id),
    CONSTRAINT fk_rol_permiso_rol FOREIGN KEY (rol_id) REFERENCES rol (id),
    CONSTRAINT fk_rol_permiso_permiso FOREIGN KEY (permiso_id) REFERENCES permiso (id)
);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    rol_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    apellidos VARCHAR(160) NOT NULL,
    dni VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    foto_url VARCHAR(2048),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuario_centro FOREIGN KEY (centro_id) REFERENCES centro (id),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol (id)
);

CREATE TABLE tutor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    apellidos VARCHAR(160) NOT NULL,
    dni VARCHAR(20) NOT NULL,
    email VARCHAR(254) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tutor_centro_dni UNIQUE (centro_id, dni),
    CONSTRAINT fk_tutor_centro FOREIGN KEY (centro_id) REFERENCES centro (id)
);

CREATE TABLE persona_autorizada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    CONSTRAINT fk_persona_autorizada_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE contacto_emergencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    relacion VARCHAR(80),
    CONSTRAINT fk_contacto_emergencia_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE perro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    tutor_id BIGINT,
    nombre VARCHAR(120) NOT NULL,
    raza VARCHAR(120),
    fecha_nacimiento DATE,
    tamano VARCHAR(10) NOT NULL,
    temperamento VARCHAR(1000),
    pautas_alimentacion VARCHAR(1000),
    foto_url VARCHAR(2048),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_perro_tamano CHECK (tamano IN ('PEQUENO', 'MEDIANO', 'GRANDE')),
    CONSTRAINT fk_perro_centro FOREIGN KEY (centro_id) REFERENCES centro (id),
    CONSTRAINT fk_perro_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE alergia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_id BIGINT NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_alergia_perro FOREIGN KEY (perro_id) REFERENCES perro (id)
);

CREATE TABLE medicacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_id BIGINT NOT NULL,
    medicamento VARCHAR(160) NOT NULL,
    dosis VARCHAR(255),
    pauta VARCHAR(1000) NOT NULL,
    CONSTRAINT fk_medicacion_perro FOREIGN KEY (perro_id) REFERENCES perro (id)
);

CREATE TABLE incompatibilidad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_a_id BIGINT NOT NULL,
    perro_b_id BIGINT NOT NULL,
    motivo VARCHAR(1000),
    CONSTRAINT ck_incompatibilidad_orden CHECK (perro_a_id < perro_b_id),
    CONSTRAINT uq_incompatibilidad_perros UNIQUE (perro_a_id, perro_b_id),
    CONSTRAINT fk_incompatibilidad_perro_a FOREIGN KEY (perro_a_id) REFERENCES perro (id),
    CONSTRAINT fk_incompatibilidad_perro_b FOREIGN KEY (perro_b_id) REFERENCES perro (id)
);

CREATE TABLE grupo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    sala VARCHAR(120),
    capacidad_max INTEGER NOT NULL,
    CONSTRAINT ck_grupo_capacidad CHECK (capacidad_max > 0),
    CONSTRAINT uq_grupo_centro_nombre UNIQUE (centro_id, nombre),
    CONSTRAINT fk_grupo_centro FOREIGN KEY (centro_id) REFERENCES centro (id)
);

CREATE TABLE bono (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL,
    dias_totales INTEGER NOT NULL,
    dias_restantes INTEGER NOT NULL,
    caduca_el DATE,
    CONSTRAINT ck_bono_dias_totales CHECK (dias_totales > 0),
    CONSTRAINT ck_bono_dias_restantes CHECK (dias_restantes >= 0 AND dias_restantes <= dias_totales),
    CONSTRAINT fk_bono_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_id BIGINT NOT NULL,
    bono_id BIGINT,
    grupo_id BIGINT,
    fecha DATE NOT NULL,
    modalidad VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reserva_modalidad CHECK (modalidad IN ('DIA_COMPLETO', 'MEDIA_JORNADA')),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'EN_CURSO', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT uq_reserva_perro_fecha UNIQUE (perro_id, fecha),
    CONSTRAINT fk_reserva_perro FOREIGN KEY (perro_id) REFERENCES perro (id),
    CONSTRAINT fk_reserva_bono FOREIGN KEY (bono_id) REFERENCES bono (id),
    CONSTRAINT fk_reserva_grupo FOREIGN KEY (grupo_id) REFERENCES grupo (id)
);

CREATE TABLE check_registro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    estado_mascota VARCHAR(500),
    observaciones VARCHAR(2000),
    CONSTRAINT ck_check_registro_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT fk_check_registro_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT fk_check_registro_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE registro_diario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    notas VARCHAR(2000),
    CONSTRAINT ck_registro_diario_tipo CHECK (tipo IN ('COMIDA', 'PASEO', 'JUEGO', 'DESCANSO', 'OTRO')),
    CONSTRAINT fk_registro_diario_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT fk_registro_diario_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE incidencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT,
    cita_id BIGINT,
    usuario_id BIGINT NOT NULL,
    gravedad VARCHAR(10) NOT NULL,
    descripcion VARCHAR(2000) NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    CONSTRAINT ck_incidencia_gravedad CHECK (gravedad IN ('LEVE', 'MODERADA', 'GRAVE')),
    CONSTRAINT ck_incidencia_referencia CHECK (reserva_id IS NOT NULL OR cita_id IS NOT NULL),
    CONSTRAINT fk_incidencia_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id),
    CONSTRAINT fk_incidencia_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id BIGINT NOT NULL,
    tipo VARCHAR(80) NOT NULL,
    mensaje VARCHAR(2000) NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notificacion_tutor FOREIGN KEY (tutor_id) REFERENCES tutor (id)
);

CREATE TABLE resumen_diario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id BIGINT NOT NULL,
    destinatario VARCHAR(10) NOT NULL,
    texto_ia VARCHAR(4000) NOT NULL,
    generado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_resumen_diario_destinatario CHECK (destinatario IN ('TUTOR', 'CUIDADOR', 'GERENTE')),
    CONSTRAINT fk_resumen_diario_reserva FOREIGN KEY (reserva_id) REFERENCES reserva (id)
);

CREATE TABLE servicio_peluqueria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_id BIGINT NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    duracion_min INTEGER NOT NULL,
    precio NUMERIC(10, 2) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_servicio_peluqueria_duracion CHECK (duracion_min > 0),
    CONSTRAINT ck_servicio_peluqueria_precio CHECK (precio >= 0),
    CONSTRAINT fk_servicio_peluqueria_centro FOREIGN KEY (centro_id) REFERENCES centro (id)
);

CREATE TABLE ficha_peluqueria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_id BIGINT NOT NULL UNIQUE,
    tipo_pelo VARCHAR(120),
    notas VARCHAR(2000),
    CONSTRAINT fk_ficha_peluqueria_perro FOREIGN KEY (perro_id) REFERENCES perro (id)
);

CREATE TABLE disponibilidad_peluquero (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    dia_semana SMALLINT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT ck_disponibilidad_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_disponibilidad_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT fk_disponibilidad_peluquero_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE solicitud_peluqueria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centro_cliente_id BIGINT NOT NULL,
    modalidad VARCHAR(20) NOT NULL,
    direccion_servicio VARCHAR(255),
    fecha_solicitada DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADA',
    notas VARCHAR(2000),
    creada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_solicitud_peluqueria_modalidad CHECK (modalidad IN ('EN_INSTALACIONES', 'DESPLAZADO')),
    CONSTRAINT ck_solicitud_peluqueria_estado CHECK (estado IN ('SOLICITADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT fk_solicitud_peluqueria_centro FOREIGN KEY (centro_cliente_id) REFERENCES centro (id)
);

CREATE TABLE cita_peluqueria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perro_id BIGINT NOT NULL,
    peluquero_id BIGINT NOT NULL,
    solicitud_id BIGINT,
    inicio TIMESTAMP NOT NULL,
    duracion_min INTEGER NOT NULL,
    lugar VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADA',
    CONSTRAINT ck_cita_peluqueria_duracion CHECK (duracion_min > 0),
    CONSTRAINT ck_cita_peluqueria_lugar CHECK (lugar IN ('EN_INSTALACIONES', 'DESPLAZADO')),
    CONSTRAINT ck_cita_peluqueria_estado CHECK (estado IN ('SOLICITADA', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT fk_cita_peluqueria_perro FOREIGN KEY (perro_id) REFERENCES perro (id),
    CONSTRAINT fk_cita_peluqueria_peluquero FOREIGN KEY (peluquero_id) REFERENCES usuario (id),
    CONSTRAINT fk_cita_peluqueria_solicitud FOREIGN KEY (solicitud_id) REFERENCES solicitud_peluqueria (id)
);

ALTER TABLE incidencia
    ADD CONSTRAINT fk_incidencia_cita FOREIGN KEY (cita_id) REFERENCES cita_peluqueria (id);

CREATE TABLE cita_servicio (
    cita_id BIGINT NOT NULL,
    servicio_id BIGINT NOT NULL,
    CONSTRAINT pk_cita_servicio PRIMARY KEY (cita_id, servicio_id),
    CONSTRAINT fk_cita_servicio_cita FOREIGN KEY (cita_id) REFERENCES cita_peluqueria (id),
    CONSTRAINT fk_cita_servicio_servicio FOREIGN KEY (servicio_id) REFERENCES servicio_peluqueria (id)
);
